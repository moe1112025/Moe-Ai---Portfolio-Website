import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const required=['src/main.jsx','src/data/content.js','src/components/CinematicScene.jsx','src/components/CinematicScroll.jsx','src/components/MediaModal.jsx','src/styles/global.css','public/Moe-Htet-Ar-Kar-CV.pdf'];
const missing=required.filter(f=>!fs.existsSync(path.join(root,f)));
const count=(dir,ext)=>fs.readdirSync(path.join(root,dir),{withFileTypes:true}).filter(x=>x.isFile()&&x.name.endsWith(ext)).length;
const aiPdf=count('public/ai_lab','.pdf'), aiPng=count('public/ai_lab','.png'), sqlPdf=count('public/sql_lab','.pdf'), sqlPng=count('public/sql_lab','.png');
const mlSvg=count('public/assets/ml','.svg');
const text=fs.readFileSync(path.join(root,'src/main.jsx'),'utf8');
const content=fs.readFileSync(path.join(root,'src/data/content.js'),'utf8');
const banned=['visitor IP','Telegram','WhatsApp','terminal preloader','fake visitor'];
const bannedHits=banned.filter(x=>text.toLowerCase().includes(x.toLowerCase()));
if(missing.length) throw new Error(`Missing: ${missing.join(', ')}`);
if(aiPdf!==7||aiPng!==7||sqlPdf!==5||sqlPng!==5) throw new Error(`Unexpected evidence counts AI ${aiPdf}/${aiPng}, SQL ${sqlPdf}/${sqlPng}`);
if(mlSvg<13) throw new Error(`Expected at least 13 ML visual cards; found ${mlSvg}`);
if(!content.includes("export const appliedProjects") || !content.includes("export const securityProjects")) throw new Error('Project data exports missing');
if(bannedHits.length) throw new Error(`Banned legacy copy found: ${bannedHits.join(', ')}`);
console.log(`PASS: evidence AI ${aiPdf} PDF + ${aiPng} PNG; SQL ${sqlPdf} PDF + ${sqlPng} PNG; ML visuals ${mlSvg}; security projects + applied projects present; legacy gimmicks absent.`);
